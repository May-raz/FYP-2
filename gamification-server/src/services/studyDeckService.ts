export function isStudyDeckCard(m: { errorTag?: string }): boolean {
  return String(m?.errorTag ?? '').startsWith('study_');
}

export function studyCategoryLabel(errorTag: string): string {
  const map: Record<string, string> = {
    study_grammar: 'Grammar',
    study_vocabulary: 'Vocabulary',
    study_tense: 'Tense',
    study_correction: 'Correction',
    study_pronunciation: 'Pronunciation',
  };
  return map[String(errorTag)] ?? 'Grammar';
}
